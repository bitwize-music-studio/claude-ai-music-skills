class TestPlan:
    def test_everything_in_place(self, studio):
        plan = _run(album_art.get_album_art_plan("paper-boats"))
        assert plan["found"] is True
        assert plan["generator"] == "codex"
        assert plan["ready"] is True
        assert plan["problems"] == []
        assert plan["prompt"] == PROMPT
        assert plan["candidates"] == 1
        assert plan["codex"] == {
            "path": "/usr/local/bin/codex", "version": "codex-cli 0.164.0",
            "logged_in": True, "image_generation": True,
        }

    def test_it_says_where_things_will_go(self, studio):
        paths = _run(album_art.get_album_art_plan("paper-boats"))["paths"]
        assert paths == {
            "candidates_dir": str(studio.candidates_dir),
            "album_png": str(studio.audio_dir / "album.png"),
            "content_art": str(studio.album_dir / "album-art.png"),
        }

    def test_it_states_the_cost_in_words(self, studio):
        cost = _run(album_art.get_album_art_plan("paper-boats"))["cost"]
        assert "ChatGPT" in cost
        assert "1 image" in cost

    def test_the_cost_follows_the_number_of_candidates(self, studio):
        studio.set(candidates=3)
        plan = _run(album_art.get_album_art_plan("paper-boats"))
        assert plan["candidates"] == 3
        assert "3 images" in plan["cost"]

    def test_the_default_generator_is_the_user(self, studio):
        """With `manual` the art director hands over a prompt, as it always did."""
        studio.set(generator="manual")
        plan = _run(album_art.get_album_art_plan("paper-boats"))
        assert plan["generator"] == "manual"
        assert plan["ready"] is False
        assert _codes(plan, "blocking") == ["generator_manual"]
        assert plan["codex"] is None
        assert plan["prompt"] == PROMPT           # still useful to the user
        assert "artwork" in plan["problems"][0]["message"]

    def test_codex_is_not_installed(self, studio):
        studio.set(codex="")
        plan = _run(album_art.get_album_art_plan("paper-boats"))
        assert plan["ready"] is False
        assert _codes(plan, "blocking") == ["codex_not_found"]

    def test_codex_is_not_signed_in(self, studio):
        studio.set(status={"version": "codex-cli 0.164.0", "logged_in": False, "image_generation": True})
        plan = _run(album_art.get_album_art_plan("paper-boats"))
        assert _codes(plan, "blocking") == ["codex_not_logged_in"]
        assert "codex login" in plan["problems"][0]["message"]

    def test_image_generation_is_switched_off(self, studio):
        studio.set(status={"version": "codex-cli 0.164.0", "logged_in": True, "image_generation": False})
        assert _codes(_run(album_art.get_album_art_plan("paper-boats")), "blocking") == ["image_generation_off"]

    def test_what_codex_does_not_say_is_not_held_against_it(self, studio):
        """An older CLI lists no such feature; the run itself will tell."""
        studio.set(status={"version": "codex-cli 0.150.0", "logged_in": None, "image_generation": None})
        plan = _run(album_art.get_album_art_plan("paper-boats"))
        assert plan["ready"] is True
        assert _codes(plan, "blocking") == []

    @pytest.mark.parametrize("options", [
        {"prompt": TEMPLATE_PROMPT},
        {"prompt": ""},
        {"prompt": None},
    ])
    def test_no_prompt_yet(self, studio, options):
        studio.build(**options)
        plan = _run(album_art.get_album_art_plan("paper-boats"))
        assert plan["ready"] is False
        assert _codes(plan, "blocking") == ["no_prompt"]
        assert plan["prompt"] == ""
        assert "album-art-director" in plan["problems"][0]["message"]

