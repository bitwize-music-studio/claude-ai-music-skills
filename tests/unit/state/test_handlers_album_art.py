_NAME = re.compile(r"^cover-\d{8}-\d{6}-(\d)\.png$")


class TestGenerate:
    def test_one_candidate_by_default(self, studio):
        result = _run(album_art.generate_album_art("paper-boats"))
        assert result["generated"] == 1
        (candidate,) = result["candidates"]
        assert _NAME.match(Path(candidate["path"]).name)
        assert Path(candidate["path"]).parent == studio.candidates_dir
        assert (candidate["width"], candidate["height"]) == (1254, 1254)
        assert result["failed"] == []

    def test_codex_is_given_the_albums_prompt(self, studio):
        studio.build(negative="text, watermark")
        _run(album_art.generate_album_art("paper-boats"))
        (call,) = studio.calls
        assert call["codex"] == "/usr/local/bin/codex"
        assert call["prompt"] == PROMPT
        assert call["avoid"] == "text, watermark"
        assert call["dest_dir"] == studio.candidates_dir

    def test_the_configured_number_of_candidates(self, studio):
        studio.set(candidates=3)
        result = _run(album_art.generate_album_art("paper-boats"))
        assert result["generated"] == 3
        numbers = [_NAME.match(Path(c["path"]).name).group(1) for c in result["candidates"]]
        assert numbers == ["1", "2", "3"]
        assert len({c["path"] for c in result["candidates"]}) == 3

    @pytest.mark.parametrize("asked, made", [(2, 2), (9, 4), (0, 1)])
    def test_a_count_can_be_asked_for_and_is_capped_at_four(self, studio, asked, made):
        result = _run(album_art.generate_album_art("paper-boats", candidates=asked))
        assert result["generated"] == made
        assert len(studio.calls) == made

    def test_nothing_is_imported_and_the_readme_is_untouched(self, studio):
        before = (studio.album_dir / "README.md").read_text(encoding="utf-8")
        _run(album_art.generate_album_art("paper-boats", candidates=2))
        assert not (studio.audio_dir / "album.png").exists()
        assert not (studio.album_dir / "album-art.png").exists()
        assert (studio.album_dir / "README.md").read_text(encoding="utf-8") == before

    def test_it_leaves_the_choice_to_the_user(self, studio):
        result = _run(album_art.generate_album_art("paper-boats"))
        assert "import_album_art" in result["next"]
        assert "user" in result["next"].lower()

    @pytest.mark.parametrize("change, code", [
        ({"generator": "manual"}, "generator_manual"),
        ({"codex": ""}, "codex_not_found"),
        ({"status": {"version": "x", "logged_in": False, "image_generation": True}}, "codex_not_logged_in"),
    ])
    def test_nothing_is_spent_while_something_is_missing(self, studio, change, code):
        studio.set(**change)
        result = _run(album_art.generate_album_art("paper-boats"))
        assert result["generated"] == 0
        assert code in _codes(result, "blocking")
        assert studio.calls == []

    def test_nothing_is_spent_without_a_prompt(self, studio):
        studio.build(prompt=TEMPLATE_PROMPT)
        result = _run(album_art.generate_album_art("paper-boats"))
        assert result["generated"] == 0
        assert studio.calls == []

    def test_one_failure_does_not_lose_the_others(self, studio):
        studio.set(fail_on={2})
        result = _run(album_art.generate_album_art("paper-boats", candidates=3))
        assert result["generated"] == 2
        assert len(result["failed"]) == 1
        assert "without saving an image" in result["failed"][0]["error"]

    def test_the_candidates_are_opened_for_the_user(self, studio):
        result = _run(album_art.generate_album_art("paper-boats", candidates=2))
        assert studio.opened == [[c["path"] for c in result["candidates"]]]
        assert result["opened"] is True

    def test_the_viewer_can_be_left_shut(self, studio):
        result = _run(album_art.generate_album_art("paper-boats", open_viewer=False))
        assert studio.opened == []
        assert result["opened"] is False

    def test_a_viewer_that_will_not_open_is_not_a_failure(self, studio):
        studio.set(viewer_works=False)
        result = _run(album_art.generate_album_art("paper-boats"))
        assert result["generated"] == 1
        assert result["opened"] is False

    def test_nothing_is_opened_when_nothing_was_made(self, studio):
        studio.set(fail_on={1})
        result = _run(album_art.generate_album_art("paper-boats"))
        assert result["generated"] == 0
        assert studio.opened == []


