def _run(coro):
    return json.loads(asyncio.run(coro))


class MockStateCache:
    def __init__(self, state: dict) -> None:
        self._state = state

    def get_state(self) -> dict:
        return self._state

    def get_state_ref(self) -> dict:
        return self._state

    def rebuild(self) -> dict:
        return self._state


PROMPT = (
    "Create a square album cover artwork showing a small paper boat on calm teal "
    "water at dawn. Flat minimalist illustration, soft warm light."
)

TEMPLATE_PROMPT = (
    "[Prompt will be generated in the format matching your selected platform.\n"
    "Run /bitwize-music:album-art-director to create a visual concept and prompt.]"
)
TEMPLATE_NEGATIVE = "[Elements to exclude — only applicable for Leonardo.ai and Stable Diffusion]"


def _readme(prompt: str | None = PROMPT, negative: str | None = None, platform: str = "Codex") -> str:
    text = "# Paper Boats\n\n## Concept\n\nSmall songs.\n\n"
    if prompt is None:
        return text
    text += (
        "## Album Art\n\n### AI Art Platform\n"
        f"**Platform**: {platform}\n\n"
        "### Image Prompt\n*Generated by `/bitwize-music:album-art-director`.*\n\n"
        f"```\n{prompt}\n```\n\n"
    )
    if negative is not None:
        text += f"### Negative Prompt\n```\n{negative}\n```\n\n"
    return text + "## SoundCloud\n\nlater\n"


def _png(path: Path, size=(1254, 1254)) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    Image.new("RGB", size, (30, 120, 130)).save(path, "PNG")
    return path


@pytest.fixture
def studio(tmp_path: Path, monkeypatch):
    """An album on disk, a Codex that says yes to everything, and a recorder.

    Returns a namespace: ``build(**readme options)`` writes the album README;
    ``set(generator=..., candidates=..., status=..., codex=...)`` changes what
    the tools see; ``calls`` lists every image Codex was asked for; ``opened``
    lists what was sent to the viewer.
    """
    content = tmp_path / "content"
    audio = tmp_path / "audio"
    album_dir = content / "artists" / "test-artist" / "albums" / "folk" / "paper-boats"
    album_dir.mkdir(parents=True)
    audio_dir = audio / "artists" / "test-artist" / "albums" / "folk" / "paper-boats"

    state = {
        "version": 2,
        "config": {
            "content_root": str(content), "audio_root": str(audio),
            "documents_root": str(tmp_path / "docs"), "artist_name": "test-artist",
        },
        "albums": {"paper-boats": {
            "title": "Paper Boats", "genre": "folk", "status": "In Progress",
            "path": str(album_dir), "tracks": {},
        }},
        "session": {},
    }
    orig_cache = _shared_mod.cache
    _shared_mod.cache = MockStateCache(state)

    box = types.SimpleNamespace(
        album_dir=album_dir, audio_dir=audio_dir,
        candidates_dir=audio_dir / "artwork-candidates",
        settings={"generator": "codex", "candidates": 1, "codex_path": ""},
        codex="/usr/local/bin/codex",
        status={"version": "codex-cli 0.164.0", "logged_in": True, "image_generation": True},
        calls=[], opened=[], fail_on=set(), viewer_works=True,
    )

    def build(**options) -> None:
        (album_dir / "README.md").write_text(_readme(**options), encoding="utf-8")

    def configure(**changes) -> None:
        for key, value in changes.items():
            if key in ("generator", "candidates", "codex_path"):
                box.settings[key] = value
            else:
                setattr(box, key, value)

    def fake_generate(codex, prompt, dest_dir, filename, *, avoid="", **kwargs):
        box.calls.append({"codex": codex, "prompt": prompt, "dest_dir": Path(dest_dir),
                          "filename": filename, "avoid": avoid})
        if len(box.calls) in box.fail_on:
            return {"ok": False, "error": "Codex finished (exit 1) without saving an image", "seconds": 3}
        _png(Path(dest_dir) / filename)
        return {"ok": True, "path": str(Path(dest_dir) / filename), "width": 1254,
                "height": 1254, "seconds": 50, "saved_by": "codex"}

    def fake_open(paths):
        box.opened.append([str(p) for p in paths])
        return box.viewer_works

    monkeypatch.setattr(album_art, "_settings", lambda: dict(box.settings))
    monkeypatch.setattr(album_art.codex_art, "find_codex", lambda configured="", **kw: box.codex)
    monkeypatch.setattr(album_art.codex_art, "codex_status", lambda codex, **kw: dict(box.status))
    monkeypatch.setattr(album_art.codex_art, "generate_image", fake_generate)
    monkeypatch.setattr(album_art, "_open_in_viewer", fake_open)

    box.build = build
    box.set = configure
    build()
    yield box
    _shared_mod.cache = orig_cache


def _codes(result: dict, severity: str | None = None) -> list[str]:
    return [p["code"] for p in result["problems"] if severity is None or p["severity"] == severity]


