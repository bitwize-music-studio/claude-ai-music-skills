class TestImport:
    def test_the_chosen_image_becomes_the_albums_cover(self, studio):
        source = _png(studio.candidates_dir / "cover-20261110-101500-1.png")
        result = _run(album_art.import_album_art("paper-boats", str(source)))
        assert result["imported"] is True
        with Image.open(studio.audio_dir / "album.png") as cover:
            assert cover.size == (3000, 3000)
        with Image.open(studio.album_dir / "album-art.png") as kept:
            assert kept.size == (1254, 1254)       # the copy in git stays small
        assert result["album_png"] == str(studio.audio_dir / "album.png")
        assert result["content_art"] == str(studio.album_dir / "album-art.png")

    def test_it_says_the_cover_was_enlarged(self, studio):
        source = _png(studio.candidates_dir / "c.png")
        result = _run(album_art.import_album_art("paper-boats", str(source)))
        assert result["size"] == [3000, 3000]
        assert result["source_size"] == [1254, 1254]
        assert result["enlarged"] is True

    def test_a_candidate_can_be_named_without_its_folder(self, studio):
        _png(studio.candidates_dir / "cover-20261110-101500-2.png")
        result = _run(album_art.import_album_art("paper-boats", "cover-20261110-101500-2.png"))
        assert result["imported"] is True

    def test_an_image_from_anywhere_else_works_too(self, studio, tmp_path):
        """Art made in ChatGPT or Midjourney and downloaded is filed the same way."""
        source = _png(tmp_path / "Downloads" / "my cover.png", (3200, 3200))
        result = _run(album_art.import_album_art("paper-boats", str(source)))
        assert result["imported"] is True
        assert result["enlarged"] is False

    def test_an_existing_cover_is_kept_unless_replacing_is_asked_for(self, studio):
        old = _png(studio.audio_dir / "album.png", (3000, 3000)).read_bytes()
        source = _png(studio.candidates_dir / "c.png")
        result = _run(album_art.import_album_art("paper-boats", str(source)))
        assert result["imported"] is False
        assert "replace" in result["error"]
        assert (studio.audio_dir / "album.png").read_bytes() == old
        assert not (studio.album_dir / "album-art.png").exists()

    def test_an_existing_copy_in_the_album_folder_also_blocks(self, studio):
        _png(studio.album_dir / "album-art.png")
        source = _png(studio.candidates_dir / "c.png")
        result = _run(album_art.import_album_art("paper-boats", str(source)))
        assert result["imported"] is False
        assert not (studio.audio_dir / "album.png").exists()

    def test_replacing_overwrites_both_files(self, studio):
        _png(studio.audio_dir / "album.png", (3000, 3000))
        _png(studio.album_dir / "album-art.png", (800, 800))
        source = _png(studio.candidates_dir / "c.png")
        result = _run(album_art.import_album_art("paper-boats", str(source), replace=True))
        assert result["imported"] is True
        with Image.open(studio.album_dir / "album-art.png") as kept:
            assert kept.size == (1254, 1254)

    @pytest.mark.parametrize("make, fragment", [
        (lambda d: _png(d / "wide.png", (1536, 1024)), "not square"),
        (lambda d: (d / "note.png").write_text("hello") and (d / "note.png"), "not an image"),
        (lambda d: d / "gone.png", "not found"),
    ])
    def test_a_file_that_cannot_be_a_cover_changes_nothing(self, studio, make, fragment):
        studio.candidates_dir.mkdir(parents=True, exist_ok=True)
        source = make(studio.candidates_dir)
        result = _run(album_art.import_album_art("paper-boats", str(source)))
        assert result["imported"] is False
        assert fragment in result["error"]
        assert not (studio.audio_dir / "album.png").exists()
        assert not (studio.album_dir / "album-art.png").exists()

    def test_an_unknown_album(self, studio):
        result = _run(album_art.import_album_art("no-such-album", "x.png"))
        assert result.get("found") is False or "error" in result


